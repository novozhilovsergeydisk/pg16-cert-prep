-- Архив прежних версий: 24 вопросов тем 09–13 перед миграцией 116 (исправление странностей, materials/drafts/oddities-09-13.md).
-- Таблица question_archive создана миграцией 104; сайт её не читает.
-- Повторный запуск безопасен: вопрос копируется, только если его копии с этой причиной ещё нет. Вопросы ищутся по прежнему тексту:
-- номера на сервере и локально различаются. После миграции 116 прежних текстов уже нет, проверка в конце убедится, что в архиве все 24 копий.

BEGIN;
SET LOCAL standard_conforming_strings = on;
LOCK TABLE questions IN SHARE ROW EXCLUSIVE MODE;

INSERT INTO question_archive (question_id, question_text, options, correct_answer, explanation, option_notes, reason)
SELECT q.id, q.question_text, q.options, q.correct_answer, q.explanation, q.option_notes, 'Темы 09–13: исправлены странности (миграция 116)'
FROM questions q
JOIN categories c ON c.id = q.category_id AND left(c.name, 3) IN ('09.', '10.', '11.', '12.', '13.')
WHERE q.question_text IN (
    'Чем information_schema отличается от pg_catalog?',
    'Для чего служат табличные пространства?',
    'Зачем внутри каталога пользовательского ТП есть подкаталог с версией сервера?',
    'Для каких объектов существует слой инициализации (init)?',
    'Какое представление показывает текущую активность обслуживающих и фоновых процессов?',
    'За ходом какой команды позволяет следить представление pg_stat_progress_vacuum?',
    'Какой парольный метод аутентификации рекомендуется использовать?',
    'Какая привилегия базы данных разрешает подключение к ней?',
    'Что разрешает привилегия USAGE на схему?',
    'Какие таблицы системного каталога общие для всего кластера?',
    'Допишите команду, чтобы создать таблицу, изменения которой не пишутся в журнал предзаписи и которая доступна другим сеансам этой базы:
```
CREATE ___ TABLE t (id int);
```',
    'Допишите команду, чтобы длинные значения выносились в TOAST без сжатия:
```
ALTER TABLE t ALTER COLUMN body SET STORAGE ___;
```',
    'Допишите команду перед установкой расширения pg_stat_statements (список shared_preload_libraries пока пуст; после команды нужен перезапуск сервера):
```
ALTER SYSTEM SET shared_preload_libraries = ___;
```',
    'Какие параметры можно задать для табличного пространства командой ALTER TABLESPACE … SET?',
    'Как объекты хранятся внутри каталога табличного пространства?',
    'Как называется первый файл основного слоя постоянной таблицы?',
    'Значение уже вынесено в TOAST. UPDATE изменяет другой столбец, не затрагивая столбец с вынесенным значением. Что происходит в toast-таблице?',
    'Сервер собран с поддержкой lz4. Допишите команду, задающую lz4 как метод сжатия TOAST по умолчанию в сеансе:
```
SET default_toast_compression = ___;
```',
    'Какое ограничение есть у анализатора журналов pgBadger?',
    'Коллектор сообщений включён, журнал пишется в одном формате (log_destination = ''stderr''). Допишите маску имени файла, чтобы при ротации раз в час и log_truncate_on_rotation = on получалось 24 файла в сутки:
```
log_filename = ''postgresql-___.log''
```',
    'Какая привилегия нужна, чтобы роль могла создавать временные таблицы в базе данных?',
    'Почему недостаточно один раз отозвать у public привилегию EXECUTE на все подпрограммы?',
    'Какие из перечисленных ролей входят в число предопределённых в PostgreSQL 16?',
    'Эту строку помещают первой в pg_hba.conf. Допишите метод, чтобы запретить роли mallory TCP-подключения к любой базе с любого адреса:
```
# TYPE  DATABASE  USER     ADDRESS  METHOD
host    all       mallory  all      ___
```'
)
AND NOT EXISTS (SELECT 1 FROM question_archive a WHERE a.question_id = q.id AND a.reason = 'Темы 09–13: исправлены странности (миграция 116)');

DO $check$
DECLARE n integer;
BEGIN
    SELECT count(*) INTO n FROM question_archive WHERE reason = 'Темы 09–13: исправлены странности (миграция 116)';
    IF n <> 24 THEN
        RAISE EXCEPTION 'В архиве % копий вместо 24: прежние тексты вопросов не найдены', n;
    END IF;
END
$check$;

COMMIT;
