-- Уточнение двух вопросов после повторной независимой проверки.
-- Вопросы ищутся по тексту после миграции 009. Правильные ответы не меняются.
-- Повторный запуск безопасен: итоговая проверка подтверждает новое состояние.

BEGIN;

-- 06. Очистка: защитная очистка от переполнения работает и при выключенном track_counts
UPDATE questions SET
    question_text = 'Отключение какого параметра, кроме autovacuum, останавливает обычную автоочистку?'
WHERE question_text = 'Отключение какого параметра, кроме autovacuum, тоже выключает автоочистку?'
  AND correct_answer = 'A'
  AND options ->> 'A' = 'track_counts';

-- 08. Базы данных и схемы: схемы без доступа пропускаются, временные таблицы попадают в pg_temp
UPDATE questions SET
    question_text = 'В какую схему попадёт новая постоянная таблица, созданная без указания схемы?',
    options = jsonb_set(options, '{D}', to_jsonb('В первую существующую и доступную схему из явно указанных в пути поиска'::text)),
    explanation = 'Несуществующие схемы и схемы без права USAGE пропускаются, а для создания таблицы нужно право CREATE в выбранной схеме. Временные таблицы создаются в pg_temp.'
WHERE question_text = 'В какую схему попадёт новый объект, созданный без квалификатора?'
  AND correct_answer = 'D'
  AND options ->> 'D' = 'В первую существующую схему из явно указанных в пути поиска';

DO $check$
DECLARE n integer;
BEGIN
    SELECT count(*) INTO n FROM questions WHERE
        (question_text = 'Отключение какого параметра, кроме autovacuum, останавливает обычную автоочистку?'
            AND correct_answer = 'A' AND options ->> 'A' = 'track_counts')
     OR (question_text = 'В какую схему попадёт новая постоянная таблица, созданная без указания схемы?'
            AND correct_answer = 'D'
            AND options ->> 'D' = 'В первую существующую и доступную схему из явно указанных в пути поиска'
            AND explanation LIKE 'Несуществующие схемы и схемы без права USAGE%');
    IF n <> 2 THEN
        RAISE EXCEPTION 'Ожидалось 2 исправленных вопроса, найдено %', n;
    END IF;
END
$check$;

COMMIT;
