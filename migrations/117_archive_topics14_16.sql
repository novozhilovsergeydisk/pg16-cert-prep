-- Архив прежних версий: 16 вопросов тем 14–16 перед миграцией 118 (исправление странностей, materials/drafts/oddities-14-16.md).
-- Таблица question_archive создана миграцией 104; сайт её не читает.
-- Повторный запуск безопасен: вопрос копируется, только если его копии с этой причиной ещё нет. Вопросы ищутся по прежнему тексту:
-- номера на сервере и локально различаются. После миграции 118 прежних текстов уже нет, проверка в конце убедится, что в архиве все 16 копий.

BEGIN;
SET LOCAL standard_conforming_strings = on;
LOCK TABLE questions IN SHARE ROW EXCLUSIVE MODE;

INSERT INTO question_archive (question_id, question_text, options, correct_answer, explanation, option_notes, reason)
SELECT q.id, q.question_text, q.options, q.correct_answer, q.explanation, q.option_notes, 'Темы 14–16: исправлены странности (миграция 118)'
FROM questions q
JOIN categories c ON c.id = q.category_id AND left(c.name, 3) IN ('14.', '15.', '16.')
WHERE q.question_text IN (
    'Какое преимущество у логической резервной копии?',
    'Чем \copy в psql отличается от SQL-команды COPY при работе с файлом?',
    'Из какого шаблона рекомендуется создавать базу для восстановления из pg_dump?',
    'Какая совместимость серверов нужна для физической репликации?',
    'Что даёт включение hot_standby_feedback?',
    'На какой момент можно восстановить данные из обычной логической копии?',
    'Какие журналы предзаписи нужны, чтобы восстановить горячую копию файлов кластера?',
    'Зачем при резервном копировании по протоколу репликации используется слот репликации?',
    'Когда сегмент журнала попадает в файловый архив?',
    'Какие потери возможны при восстановлении из архива, который наполнялся командой archive_command?',
    'Допишите команду archive_command, чтобы сегмент копировался в архив под своим именем:
```
archive_command = ''cp %p /mnt/archive/___''
```',
    'Гарантируется ли согласованность данных, если приложение читает то с основного сервера, то с реплик?',
    'Какие два источника журнальных записей могут конфликтовать с запросом на реплике?',
    'Что позволяет сгладить проблему с долгими транзакциями при логической репликации?',
    'Как избежать конфликтов уникальных ключей из-за того, что значения последовательностей не реплицируются?',
    'Почему для обновления основной версии без прерывания обслуживания не подходит физическая репликация?'
)
AND NOT EXISTS (SELECT 1 FROM question_archive a WHERE a.question_id = q.id AND a.reason = 'Темы 14–16: исправлены странности (миграция 118)');

DO $check$
DECLARE n integer;
BEGIN
    SELECT count(*) INTO n FROM question_archive WHERE reason = 'Темы 14–16: исправлены странности (миграция 118)';
    IF n <> 16 THEN
        RAISE EXCEPTION 'В архиве % копий вместо 16: прежние тексты вопросов не найдены', n;
    END IF;
END
$check$;

COMMIT;
