-- Замена двух вопросов «выберите несколько», текст которых повторял вопросы с одним ответом.
-- Вопросы ищутся по тексту и по признаку «несколько ответов» (номера в базах различаются).
-- Повторный запуск безопасен: заменённые вопросы уже не находятся, а итоговая проверка
-- подтверждает новое состояние.

BEGIN;

-- 08. Базы данных и схемы
UPDATE questions SET
    question_text = 'Что верно для шаблонов баз данных и базы postgres?',
    options = '{"A": "База postgres обязательна для работы кластера", "B": "Шаблон template1 используется по умолчанию при создании новой базы", "C": "Если шаблон не указан, новая база создаётся из template0", "D": "Шаблон template0 не должен изменяться"}'::jsonb,
    correct_answer = 'BD',
    explanation = 'Объекты и расширения, добавленные в template1, попадают в каждую новую базу. Шаблон template0 нужен как чистый и не меняется. База postgres не обязательна, но некоторые утилиты предполагают её наличие.'
WHERE question_text = 'Какие базы данных создаются при инициализации кластера?'
  AND length(correct_answer) > 1;

-- 10. Табличные пространства
UPDATE questions SET
    question_text = 'Что верно для табличного пространства по умолчанию баз данных, созданных при инициализации кластера?',
    options = '{"A": "При стандартных настройках в нём создаются объекты, если табличное пространство не указано явно", "B": "Оно всегда совпадает с pg_global", "C": "Это табличное пространство pg_default", "D": "Его нельзя изменить после создания базы"}'::jsonb,
    correct_answer = 'AC',
    explanation = 'У каждой базы есть табличное пространство по умолчанию, у баз после инициализации кластера это pg_default. Его можно изменить командой ALTER DATABASE ... SET TABLESPACE, а в pg_global хранятся только общие для кластера объекты.'
WHERE question_text = 'Какие табличные пространства создаются при инициализации кластера?'
  AND length(correct_answer) > 1;

DO $check$
DECLARE n integer;
BEGIN
    SELECT count(*) INTO n FROM questions WHERE
        (question_text = 'Что верно для шаблонов баз данных и базы postgres?' AND correct_answer = 'BD')
     OR (question_text = 'Что верно для табличного пространства по умолчанию баз данных, созданных при инициализации кластера?' AND correct_answer = 'AC');
    IF n <> 2 THEN
        RAISE EXCEPTION 'Ожидалось 2 заменённых вопроса, найдено %', n;
    END IF;
END
$check$;

COMMIT;
