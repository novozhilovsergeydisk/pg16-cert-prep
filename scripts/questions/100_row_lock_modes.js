const docs = 'https://www.postgresql.org/docs/16/';
const source = (...pages) => { questions.at(-1).sources = pages; };
const rowLocks = docs + 'explicit-locking.html#LOCKING-ROWS';

S('17', 'Какую блокировку строки берёт команда DELETE?', [
    ['FOR KEY SHARE', false, 'Самый слабый режим: его берёт проверка внешнего ключа, и он сам запрещает удаление.'],
    ['FOR SHARE', false, 'Разделяемый режим для чтения: он сам запрещает изменять и удалять строку.'],
    ['FOR UPDATE', true, 'Удаление требует самого сильного режима: он несовместим со всеми остальными.'],
    ['FOR NO KEY UPDATE', false, 'Этот режим берёт UPDATE, который не меняет ключевые столбцы.'],
], 'DELETE и UPDATE, меняющий ключевые столбцы (первичного ключа или уникального индекса, на который может ссылаться внешний ключ), берут блокировку FOR UPDATE. Остальные UPDATE берут более слабую FOR NO KEY UPDATE, чтобы не мешать проверкам внешних ключей.');
source(rowLocks, docs + 'sql-select.html#SQL-FOR-UPDATE-SHARE');

S('17', 'В дочернюю таблицу вставляют строку со ссылкой на родительскую. В каком режиме проверка внешнего ключа блокирует родительскую строку?', [
    ['FOR UPDATE', false, 'Этот режим помешал бы даже изменению неключевых столбцов родительской строки.'],
    ['FOR NO KEY UPDATE', false, 'Так блокирует строку UPDATE, а не проверка внешнего ключа.'],
    ['FOR SHARE', false, 'Этот режим запретил бы и изменение неключевых столбцов, поэтому проверка берёт более слабый.'],
    ['FOR KEY SHARE', true, 'Проверке нужно лишь, чтобы строка и её ключ не исчезли до конца транзакции.'],
], 'Проверка внешнего ключа выполняет для родительской строки запрос с FOR KEY SHARE. Пока вставляющая транзакция не завершится, родительскую строку нельзя удалить или изменить её ключ, но неключевые столбцы менять можно.');
source(rowLocks, docs + 'ddl-constraints.html#DDL-CONSTRAINTS-FK');

M('17', 'В таблице t первичный ключ id, других уникальных индексов нет. Транзакция A выполнила для строки SELECT … FOR KEY SHARE и не завершилась. Какие действия другой транзакции с этой строкой выполнятся без ожидания?', [
    ['UPDATE, меняющий неключевой столбец', true, 'Он берёт FOR NO KEY UPDATE, а этот режим совместим с FOR KEY SHARE.'],
    ['DELETE этой строки по первичному ключу', false, 'Удаление берёт FOR UPDATE и ждёт: FOR KEY SHARE запрещает удалять строку.'],
    ['UPDATE, меняющий значение первичного ключа', false, 'Изменение ключа берёт FOR UPDATE и ждёт завершения A.'],
    ['SELECT … FOR SHARE этой строки', true, 'Разделяемые режимы совместимы друг с другом.'],
], 'FOR KEY SHARE конфликтует только с FOR UPDATE: он защищает строку от удаления и от изменения ключа, но разрешает обычные UPDATE и другие разделяемые блокировки.');
source(rowLocks);

S('17', 'Чем блокировка FOR SHARE отличается от FOR KEY SHARE?', [
    ['FOR SHARE не даёт менять и неключевые столбцы', true, 'FOR SHARE конфликтует с FOR NO KEY UPDATE, то есть с обычным UPDATE; FOR KEY SHARE с ним совместим.'],
    ['FOR KEY SHARE не мешает удалить эту строку', false, 'Мешает: DELETE берёт FOR UPDATE, а с ним FOR KEY SHARE несовместим.'],
    ['FOR SHARE несовместим с другим FOR SHARE', false, 'Совместим: несколько транзакций могут одновременно держать FOR SHARE на одной строке.'],
    ['FOR KEY SHARE ждёт завершения чужого FOR SHARE', false, 'Не ждёт: эти режимы совместимы.'],
], 'Оба режима разделяемые и запрещают удаление строки и изменение ключа. FOR SHARE строже: он запрещает и обычный UPDATE. FOR KEY SHARE пропускает UPDATE, не меняющий ключевые столбцы, поэтому его и использует проверка внешнего ключа.');
source(rowLocks);

