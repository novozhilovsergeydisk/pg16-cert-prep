#!/bin/bash
# Независимая проверка новых вопросов через Codex: слепые ответы и проверка пояснений.
#
#   scripts/codex-check.sh <каталог проверки вне проекта>
#
# Каталог готовит gen-questions.js --export: в <каталог>/work лежат batch.json (без ключей)
# и notes.json (с ключами и пояснениями). Codex работает только в <каталог>/work, в режиме
# «только чтение», без доступа к проекту и .env. Результаты: <каталог>/work/out/*.txt.
set -euo pipefail
DIR=$(cd "${1:?укажите каталог проверки}" && pwd)
PROJECT=$(cd "$(dirname "$0")/.." && pwd)
case "$DIR/" in "$PROJECT"/*) echo "Каталог проверки должен быть вне проекта" >&2; exit 1;; esac
W="$DIR/work"
test -f "$W/batch.json" && test -f "$W/notes.json" || { echo "Нет batch.json или notes.json в $W" >&2; exit 1; }
if grep -q '"correct"' "$W/batch.json"; then echo "batch.json не должен содержать ключей" >&2; exit 1; fi
node "$PROJECT/scripts/extract-course-text.js" "$W/course" >/dev/null
mkdir -p "$W/out"

cat > "$W/prompt-blind.md" <<'PROMPT'
Ты независимый проверяющий вопросов тренажёра по PostgreSQL 16 (курс DBA1 компании Postgres Professional).

ЗАДАНИЕ. В файле ./batch.json лежит список вопросов. У каждого: id, topic, choose (сколько вариантов нужно выбрать), question, options (ключи A, B, C, D). Ответь на КАЖДЫЙ вопрос самостоятельно, опираясь на источники, а не на догадки.

ИСТОЧНИКИ (по приоритету):
1. ./course/*.txt, тексты слайдов курса DBA1 (русский).
2. Официальная документация PostgreSQL 16 в интернете (postgresql.org/docs/16, postgrespro.ru/docs/postgresql/16), если в курсе ответа нет или нужно подтвердить синтаксис и значения по умолчанию.

ПРАВИЛА.
- Читай ТОЛЬКО ./batch.json и файлы в ./course/. Больше никакие файлы не открывай, в других каталогах ничего не ищи и не читай. Ничего не создавай и не изменяй. Сетевые запросы допустимы только для чтения документации PostgreSQL.
- Верный ответ определяется по источникам. Число правильных вариантов равно значению choose.
- Для вопросов «дополните код» (в тексте есть ___) выбери вариант, после подстановки которого команда корректна и выполняется в PostgreSQL 16.
- Если вопрос некорректен (нет верного варианта, верных больше, чем choose, формулировка двусмысленна или фактическая ошибка в варианте), всё равно выбери наиболее верный ответ и честно отметь проблему в note.

ФОРМАТ ОТВЕТА. Только JSON-массив, без пояснений до и после, по одному объекту на вопрос, в порядке id:
{"id": 123, "answer": "AC", "confidence": "high|medium|low", "source": "course:dba1_05 (коротко что именно) или docs:URL", "flag": false, "note": ""}
answer: буквы выбранных вариантов по алфавиту без разделителей. flag=true, если вопрос спорный или некорректен, тогда note обязательно объясняет почему.
PROMPT

cat > "$W/prompt-notes.md" <<'PROMPT'
Ты проверяешь пояснения к вариантам ответов в тренажёре по PostgreSQL 16 (курс DBA1 Postgres Professional).

В файле ./notes.json у каждого вопроса: question, options (A–D), correct (верные буквы) и option_notes — по одному короткому пояснению к каждому варианту: что этот вариант делает на самом деле или почему он не подходит.

ЗАДАНИЕ. Проверь фактическую точность КАЖДОГО пояснения и согласованность с ключом. Источники: ./course/*.txt (слайды курса DBA1) и официальная документация PostgreSQL 16 (postgresql.org/docs/16, postgrespro.ru/docs/postgresql/16).

ПРАВИЛА.
- Читай ТОЛЬКО ./notes.json и файлы в ./course/. Никакие другие файлы не открывай и не ищи. Ничего не создавай и не изменяй.
- Отмечай только реальные проблемы: фактическая ошибка, неточность, противоречие ключу, утверждение, верное лишь при оговорке, которой нет. Стиль и формулировки на вкус не оценивай.

ФОРМАТ ОТВЕТА. Только JSON-массив, без текста до и после; только для вопросов, где есть проблемы (пустой массив, если проблем нет):
{"id": 1001, "letter": "B", "problem": "что именно неверно", "fix": "как исправить пояснение (одна фраза)", "source": "course:… или docs:URL"}
Для проблемы в самом вопросе или ключе используй letter = "Q".
PROMPT

echo "$(date +%H:%M:%S) слепая проверка"
codex --search exec --skip-git-repo-check -s read-only --ephemeral -C "$W" -o "$W/out/blind.txt" - < "$W/prompt-blind.md" > "$W/out/blind.log" 2>&1
echo "$(date +%H:%M:%S) проверка пояснений"
codex --search exec --skip-git-repo-check -s read-only --ephemeral -C "$W" -o "$W/out/notes.txt" - < "$W/prompt-notes.md" > "$W/out/notes.log" 2>&1
echo "$(date +%H:%M:%S) готово; обращений к .env, ключам или проекту в журналах: $(cat "$W"/out/*.log | grep -ciE '\.env|keys\.json|Projects/pg16' || true)"
